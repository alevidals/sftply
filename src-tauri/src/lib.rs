/// Generate the TypeScript bindings. Invoked by `cargo run --example
/// export-bindings` and, in debug builds, on startup.
pub fn export_bindings() -> Result<(), Box<dyn std::error::Error>> {
    specta_builder().export(
        Typescript::default().header(
            "/* eslint-disable */\n// @ts-nocheck\n// This file is generated by tauri-specta. Do not edit it by hand.",
        ),
        "../src/lib/ipc/bindings.ts",
    )?;
    Ok(())
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = specta_builder();

    #[cfg(debug_assertions)]
    export_bindings().expect("failed to export TypeScript bindings");

    let invoke_handler = builder.invoke_handler();

    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_window_state::Builder::default().build())
        .setup(move |app| {
            let paths = AppPaths::resolve(app.handle())?;
            let log_guard = logging::init(&paths)?;
            let (settings, settings_warning) = SettingsStore::load(paths.settings_file.clone());
            let (connections, connections_warning) =
                ConnectionStore::load(paths.connections_file.clone());
            let (known_hosts, known_hosts_warning) =
                KnownHostsStore::load(paths.known_hosts_file.clone());
            let (history, history_warning) =
                TransferHistoryStore::load(paths.transfer_history_file.clone());
            let warnings = settings_warning
                .into_iter()
                .chain(connections_warning)
                .chain(known_hosts_warning)
                .chain(history_warning)
                .collect();

            app.manage(AppState::new(
                paths,
                settings,
                connections,
                known_hosts,
                std::sync::Arc::new(history),
                log_guard,
                warnings,
            ));
            builder.mount_events(app);

            tracing::info!(version = env!("CARGO_PKG_VERSION"), "sftply starting");

            Ok(())
        })
        .invoke_handler(invoke_handler)
        .run(tauri::generate_context!())
        .expect("error while running sftply");
}
